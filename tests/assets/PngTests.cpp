void expectPixels(const Result<ImageData>& image, u32 width, u32 height,
                  const std::vector<u8>& expected, int tolerance = 0) {
    ASSERT_TRUE(image.has_value()) << image.error().message;
    EXPECT_EQ(image->width, width);
    EXPECT_EQ(image->height, height);
    ASSERT_EQ(image->pixels.size(), expected.size());
    for (usize i = 0; i < expected.size(); ++i) {
        EXPECT_NEAR(image->pixels[i], expected[i], tolerance) << "byte " << i;
    }
}

