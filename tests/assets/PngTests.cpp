TEST(Png, DecodesReferenceFiles) {
    expectPixels(decodePng(kRgba16Interlaced), 5, 4, kRgba16InterlacedRgba, 1);
    expectPixels(decodePng(kGray1Interlaced), 9, 3, kGray1InterlacedRgba);
    expectPixels(decodePng(kPalette4Transparent), 6, 3, kPalette4TransparentRgba);
    expectPixels(decodePng(kRgbColorKey), 3, 2, kRgbColorKeyRgba);
}

TEST(Png, RoundTripsTheEngineEncoder) {
    const ImageData source = makeCheckerboard(70, 7, {12, 34, 56, 255}, {200, 100, 50, 128});
    const auto decoded = decodePng(encodePng(source));
    ASSERT_TRUE(decoded.has_value()) << decoded.error().message;
    EXPECT_EQ(decoded->width, source.width);
    EXPECT_EQ(decoded->height, source.height);
    EXPECT_EQ(decoded->pixels, source.pixels);
}

TEST(Png, RejectsMalformedFiles) {
    EXPECT_FALSE(decodePng({}).has_value());
    EXPECT_FALSE(decodePng(std::vector<u8>(kRgbColorKey.begin(), kRgbColorKey.begin() + 8)).has_value());

    std::vector<u8> badCrc = kRgbColorKey;
    badCrc[29] ^= 0xff;  // IHDR CRC
    const auto crc = decodePng(badCrc);
    ASSERT_FALSE(crc.has_value());
    EXPECT_NE(crc.error().message.find("CRC"), std::string::npos);

    // Truncation anywhere fails cleanly.
    for (usize size = 0; size < kPalette4Transparent.size() - 12; ++size) {
        const std::vector<u8> truncated(kPalette4Transparent.begin(),
                                        kPalette4Transparent.begin() + static_cast<std::ptrdiff_t>(size));
        EXPECT_FALSE(decodePng(truncated).has_value()) << size << " bytes";
    }
}
